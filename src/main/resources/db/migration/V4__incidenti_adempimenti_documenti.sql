-- Fase 2: soggetto NIS, livelli di servizio attesi, utenti, incidenti, valutazioni di
-- significatività, adempimenti, versioni dei documenti, classificazione, riclassificazioni, audit.
-- Le entità JPA sono validate contro questo DDL (ddl-auto=validate).
-- Tutti gli istanti sono TIMESTAMP WITH TIME ZONE: i termini di 24 h e 72 h si contano in ore
-- reali, indipendentemente dal passaggio tra ora solare e ora legale.

-- Soggetto NIS che notifica. Il tipo decide se si applica la categoria IS-4 (solo essenziali).
CREATE TABLE soggetto (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    denominazione        VARCHAR(255)  NOT NULL,
    codice_fiscale       VARCHAR(16)   NOT NULL UNIQUE,
    tipo                 VARCHAR(20)   NOT NULL,
    settore              VARCHAR(255)  NOT NULL,
    motivazione_tipo     VARCHAR(1000) NOT NULL,
    referente_nome       VARCHAR(255)  NOT NULL,
    referente_email      VARCHAR(255)  NOT NULL,
    referente_telefono   VARCHAR(50)   NOT NULL,
    CONSTRAINT ck_soggetto_tipo CHECK (tipo IN ('ESSENZIALE', 'IMPORTANTE'))
);

-- Livelli di servizio attesi (SL), definiti in autonomia dal soggetto per i servizi critici
-- (misura DE.CM-01, punto 2). Non coincidono necessariamente con gli SLA contrattuali.
-- Sono la base della categoria IS-3 (violazione dei livelli di servizio attesi).
CREATE TABLE livello_servizio (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soggetto_id                 BIGINT        NOT NULL REFERENCES soggetto (id),
    servizio                    VARCHAR(40)   NOT NULL,
    descrizione                 VARCHAR(255)  NOT NULL,
    max_indisponibilita_minuti  INTEGER       NOT NULL,
    max_degrado_minuti          INTEGER       NOT NULL,
    fonte                       VARCHAR(500)  NOT NULL,
    CONSTRAINT uq_livello_servizio UNIQUE (soggetto_id, servizio)
);

CREATE TABLE utente (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)   NOT NULL UNIQUE,
    password_hash   VARCHAR(100)  NOT NULL,
    nome_completo   VARCHAR(255)  NOT NULL,
    ruolo           VARCHAR(20)   NOT NULL,
    attivo          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_utente_ruolo CHECK (ruolo IN ('OPERATORE', 'APPROVATORE'))
);

-- Incidente. rilevato_il è il primo evento rilevante per la sicurezza; conoscenza_il è il momento
-- in cui il soggetto ha evidenza (elementi oggettivi) di un incidente significativo, da cui decorrono
-- i termini di 24 h e 72 h (art. 25, c. 5, lett. a e b, D.Lgs. 138/2024). Si registra una sola volta (ADR-0003).
CREATE TABLE incidente (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codice                    VARCHAR(20)   NOT NULL UNIQUE,
    soggetto_id               BIGINT        NOT NULL REFERENCES soggetto (id),
    titolo                    VARCHAR(255)  NOT NULL,
    descrizione               VARCHAR(4000) NOT NULL,
    stato                     VARCHAR(20)   NOT NULL,
    rilevato_il               TIMESTAMP WITH TIME ZONE NOT NULL,
    registrato_il             TIMESTAMP WITH TIME ZONE NOT NULL,
    registrato_da             VARCHAR(50)   NOT NULL,
    conoscenza_il             TIMESTAMP WITH TIME ZONE,
    conoscenza_motivazione    VARCHAR(2000),
    conoscenza_registrata_il  TIMESTAMP WITH TIME ZONE,
    conoscenza_registrata_da  VARCHAR(50),
    conclusione_gestione_il   TIMESTAMP WITH TIME ZONE,
    versione                  BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_incidente_stato CHECK (stato IN ('IN_VALUTAZIONE', 'NON_SIGNIFICATIVO', 'SIGNIFICATIVO',
                                                   'DECLASSATO', 'CHIUSO')),
    CONSTRAINT ck_incidente_conoscenza CHECK (conoscenza_il IS NULL OR conoscenza_il >= rilevato_il),
    CONSTRAINT ck_incidente_conoscenza_completa CHECK (
        (conoscenza_il IS NULL AND conoscenza_motivazione IS NULL AND conoscenza_registrata_il IS NULL)
        OR (conoscenza_il IS NOT NULL AND conoscenza_motivazione IS NOT NULL AND conoscenza_registrata_il IS NOT NULL))
);

-- Storico delle valutazioni di significatività: ogni valutazione resta, con l'input usato
-- e la versione delle soglie, così la motivazione è ricostruibile anche dopo una riclassificazione.
CREATE TABLE valutazione_significativita (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id      BIGINT        NOT NULL REFERENCES incidente (id),
    eseguita_il       TIMESTAMP WITH TIME ZONE NOT NULL,
    eseguita_da       VARCHAR(50)   NOT NULL,
    soglia_set_id     BIGINT        NOT NULL REFERENCES soglia_set (id),
    servizio          VARCHAR(40)   NOT NULL,
    input_json        VARCHAR(10000) NOT NULL,
    significativo     BOOLEAN       NOT NULL,
    regole_attivate   VARCHAR(100)  NOT NULL,
    categorie_is      VARCHAR(100)  NOT NULL
);

CREATE INDEX ix_valutazione_incidente ON valutazione_significativita (incidente_id);

-- Adempimento verso il CSIRT Italia. Le scadenze non sono memorizzate: si calcolano dai fatti
-- (conoscenza, trasmissione della notifica, conclusione della gestione), così non possono
-- divergere da essi. Fa eccezione la scadenza indicata dal CSIRT per la relazione intermedia.
CREATE TABLE adempimento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id         BIGINT        NOT NULL REFERENCES incidente (id),
    tipo                 VARCHAR(30)   NOT NULL,
    progressivo          INTEGER       NOT NULL,
    stato                VARCHAR(20)   NOT NULL,
    richiesto_il         TIMESTAMP WITH TIME ZONE,
    scadenza_richiesta   TIMESTAMP WITH TIME ZONE,
    riferimento_richiesta VARCHAR(255),
    trasmesso_il         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_adempimento UNIQUE (incidente_id, tipo, progressivo),
    CONSTRAINT ck_adempimento_tipo CHECK (tipo IN ('PRE_NOTIFICA', 'NOTIFICA', 'RELAZIONE_INTERMEDIA',
                                                   'RELAZIONE_MENSILE', 'RELAZIONE_FINALE')),
    CONSTRAINT ck_adempimento_stato CHECK (stato IN ('DA_REDIGERE', 'IN_LAVORAZIONE', 'TRASMESSO'))
);

-- Versione di un documento. Una versione TRASMESSA è immutabile (controllo applicativo e test);
-- le colonne impronta_* sono riservate alla catena di hash SHA-256 della Fase 3.
CREATE TABLE versione_documento (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adempimento_id            BIGINT        NOT NULL REFERENCES adempimento (id),
    numero                    INTEGER       NOT NULL,
    stato                     VARCHAR(20)   NOT NULL,
    contenuto_json            VARCHAR(200000) NOT NULL,
    tassonomia_versione_id    BIGINT        NOT NULL REFERENCES tassonomia_versione (id),
    derivata_da_id            BIGINT        REFERENCES versione_documento (id),
    creata_il                 TIMESTAMP WITH TIME ZONE NOT NULL,
    creata_da                 VARCHAR(50)   NOT NULL,
    modificata_il             TIMESTAMP WITH TIME ZONE NOT NULL,
    modificata_da             VARCHAR(50)   NOT NULL,
    inviata_approvazione_il   TIMESTAMP WITH TIME ZONE,
    inviata_approvazione_da   VARCHAR(50),
    nota_respingimento        VARCHAR(2000),
    approvata_da              VARCHAR(50),
    trasmessa_il              TIMESTAMP WITH TIME ZONE,
    riferimento_trasmissione  VARCHAR(255),
    impronta_sha256           VARCHAR(64),
    impronta_precedente       VARCHAR(64),
    versione                  BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_versione_documento UNIQUE (adempimento_id, numero),
    CONSTRAINT ck_versione_stato CHECK (stato IN ('BOZZA', 'IN_APPROVAZIONE', 'TRASMESSO')),
    CONSTRAINT ck_versione_trasmessa CHECK (stato <> 'TRASMESSO'
        OR (trasmessa_il IS NOT NULL AND approvata_da IS NOT NULL AND riferimento_trasmissione IS NOT NULL))
);

-- Classificazione: voci della tassonomia (solo livello VALORE, imposto lato server) associate
-- a una versione del documento, non all'incidente: ogni invio conserva la propria classificazione.
CREATE TABLE classificazione (
    versione_documento_id  BIGINT NOT NULL REFERENCES versione_documento (id),
    voce_id                BIGINT NOT NULL REFERENCES tassonomia_voce (id),
    PRIMARY KEY (versione_documento_id, voce_id)
);

-- Traccia prima/dopo delle riclassificazioni (popolata nella Fase 3).
CREATE TABLE storico_riclassificazione (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidente_id         BIGINT        NOT NULL REFERENCES incidente (id),
    documento_prima_id   BIGINT        REFERENCES versione_documento (id),
    documento_dopo_id    BIGINT        REFERENCES versione_documento (id),
    significativo_prima  BOOLEAN       NOT NULL,
    significativo_dopo   BOOLEAN       NOT NULL,
    voci_prima           VARCHAR(2000) NOT NULL,
    voci_dopo            VARCHAR(2000) NOT NULL,
    motivazione          VARCHAR(2000) NOT NULL,
    registrata_il        TIMESTAMP WITH TIME ZONE NOT NULL,
    registrata_da        VARCHAR(50)   NOT NULL
);

-- Registro di audit: solo inserimenti, nessuna API di modifica o cancellazione.
CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    istante    TIMESTAMP WITH TIME ZONE NOT NULL,
    username   VARCHAR(50)   NOT NULL,
    azione     VARCHAR(50)   NOT NULL,
    entita     VARCHAR(50),
    entita_id  BIGINT,
    dettaglio  VARCHAR(2000)
);

CREATE INDEX ix_audit_entita ON audit_log (entita, entita_id);

